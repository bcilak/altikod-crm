import { test, expect } from '@playwright/test';
test('desktop sales workflow and mobile navigation', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('E-posta', { exact: true }).fill('e2e-admin@example.invalid');
  await page.getByLabel('Parola', { exact: true }).fill('E2E-only-password!42');
  await page.getByRole('button', { name: 'Giriş yap' }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.getByRole('link', { name: 'Firmalar', exact: true }).click();
  await page.getByText('Yeni firma', { exact: true }).click();
  const companyForm = page.locator('details').filter({ has: page.locator('summary', { hasText: 'Yeni firma' }) }).locator('form');
  await companyForm.getByLabel('Firma adı').fill('DEMO Tarayıcı Firması');
  await companyForm.getByLabel('Ticari unvan').fill('DEMO Tarayıcı AŞ');
  await companyForm.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await expect(page.getByRole('link', { name: 'DEMO Tarayıcı Firması', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'DEMO Tarayıcı Firması', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'DEMO Tarayıcı Firması' })).toBeVisible();
  const contact = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Kişi ekle$/ }) });
  await contact.locator('summary').click(); await contact.getByLabel('Ad', { exact: true }).fill('DEMO'); await contact.getByLabel('Soyad').fill('Yetkili'); await contact.getByRole('button', { name: 'Kaydet' }).click();
  await expect(page.getByText('DEMO Yetkili', { exact: true }).first()).toBeVisible();
  const activity = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Görüşme kaydet$/ }) });
  await activity.locator('summary').click(); await activity.getByLabel('Görüşme türü').selectOption('CALL'); await activity.getByLabel('Gerçekleşme zamanı').fill('2026-10-30T15:00'); await activity.getByLabel('Görüşme özeti').fill('DEMO İhtiyaç analizi görüşmesi'); await activity.getByRole('button', { name: 'Kaydet' }).click();
  await expect(page.getByText('DEMO İhtiyaç analizi görüşmesi', { exact: true }).first()).toBeVisible();
  const task = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Takip görevi oluştur$/ }) });
  await task.locator('summary').click(); await task.getByLabel('Görev', { exact: false }).fill('DEMO Teknik takip'); await task.getByLabel('Hedef tarih').fill('2026-11-02T14:00'); await task.getByRole('button', { name: 'Kaydet' }).click();
  await expect(task.getByRole('status')).toHaveText('İşlem tamamlandı.');
  const opportunity = page.locator('details').filter({ has: page.locator('summary', { hasText: /^Satış fırsatı aç$/ }) });
  await opportunity.locator('summary').click(); await opportunity.getByLabel('Fırsat başlığı').fill('DEMO Güvenlik projesi'); await opportunity.getByLabel('Tahmini tutar').fill('12500.50'); await opportunity.getByLabel('Sonraki aksiyon').fill('2026-11-03T10:00'); await opportunity.getByRole('button', { name: 'Kaydet' }).click();
  await page.getByRole('link', { name: 'DEMO Güvenlik projesi', exact: true }).click();
  await page.getByLabel('Yeni aşama').selectOption('QUALIFICATION'); await page.getByRole('button', { name: 'Aşamayı değiştir' }).click();
  await expect(page.getByText('Yeni fırsat → Ön değerlendirme', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Fırsatlar', exact: true }).click();
  await expect(page.locator('.deal-card')).toHaveCount(1);
  await page.screenshot({ path: 'test-results/desktop-pipeline.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Menüyü aç' }).click();
  await page.getByRole('link', { name: 'Görevler', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'DEMO Teknik takip', exact: true })).toBeVisible();
  await page.getByText('Görevi güncelle', { exact: true }).click();
  await page.locator('form').getByLabel('Durum', { exact: true }).selectOption('DONE');
  await page.locator('form').getByRole('button', { name: 'Kaydet' }).click();
  await expect(page.locator('.badge').filter({ hasText: 'Tamamlandı' })).toBeVisible();
  await page.screenshot({ path: 'test-results/mobile-tasks.png', fullPage: true });
  await page.getByRole('button', { name: 'Çıkış yap' }).click();
  await expect(page).toHaveURL(/login/);
});
