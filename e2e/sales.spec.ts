import { test, expect } from '@playwright/test';
test('quote approval PDF acceptance, handoff, CSV and responsive reports', async ({ page }) => {
  page.on('dialog', dialog => dialog.accept());
  await page.goto('/login');
  await page.getByLabel('E-posta', { exact: true }).fill('e2e-admin@example.invalid');
  await page.getByLabel('Parola', { exact: true }).fill('E2E-only-password!42');
  await page.getByRole('button', { name: 'Giriş yap' }).click(); await expect(page).toHaveURL(/dashboard/);
  const me = await (await page.request.get('/api/v1/auth/me')).json();
  const post = async (path: string, data: object) => { const response = await page.request.post(`/api/v1${path}`, { headers: { Origin: 'http://localhost:3100', 'X-CSRF-Token': me.csrfToken }, data }); expect(response.ok(), await response.text()).toBeTruthy(); return response.json(); };
  const firm = await post('/companies', { displayName: 'E2E Teklif Firması', legalName: 'E2E Teklif AŞ' });
  const opp = await post('/opportunities', { companyId: firm.id, title: 'E2E Firewall', estimatedValue: '1000', currency: 'TRY', probability: 50, nextActionAt: '2030-01-01T00:00:00Z' });
  await page.getByRole('link', { name: 'Teklifler', exact: true }).click();
  await page.getByText('Yeni teklif', { exact: true }).click();
  await page.getByLabel('Fırsat', { exact: true }).selectOption(opp.id);
  await page.getByLabel('Teklif başlığı').fill('E2E Güvenlik teklifi');
  await page.getByLabel('Açıklama', { exact: true }).fill('Firewall kurulumu');
  await page.getByLabel('Birim fiyat', { exact: true }).fill('1000');
  await page.getByLabel('Birim maliyet', { exact: true }).fill('500');
  await page.getByRole('button', { name: 'Taslağı kaydet' }).click(); await expect(page).toHaveURL(/quotes\/[a-f0-9-]+$/);
  await page.getByRole('button', { name: 'Onaya gönder', exact: true }).click();
  await page.getByRole('button', { name: 'Yönetici onayı ver', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'PDF indir', exact: true }).click();
  expect((await download).suggestedFilename()).toMatch(/SH-\d+-V1.pdf/);
  await page.getByRole('button', { name: 'Gönderildi olarak kaydet' }).click();
  await page.getByLabel('Karar', { exact: true }).selectOption('accept');
  await page.getByLabel('Müşteri kararı dayanağı / not').fill('E2E sipariş kabulü');
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await expect(page.getByText('Kazanılan işi teslimata devret →')).toBeVisible();
  await page.screenshot({ path: 'test-results/desktop-quote.png', fullPage: true });
  await page.getByText('Kazanılan işi teslimata devret →').click();
  await page.getByText('Kazanılan işi devret', { exact: true }).click();
  await page.getByLabel('Kazanılmış fırsat', { exact: true }).selectOption(opp.id);
  await page.locator('select[name="ownerId"]').selectOption(me.id);
  await page.getByLabel('Müşteri ihtiyacı ve devir özeti').fill('E2E kurulum teslimatı');
  await page.getByLabel('İlk teslimat görevi hedefi (İstanbul)').fill('2030-01-02T10:00');
  await page.getByRole('button', { name: 'Kaydet', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'E2E Firewall', exact: true })).toBeVisible();
  await page.goto('/imports'); await page.getByLabel('CSV içeriği').fill('displayName,legalName\nE2E Aktarım,E2E Aktarım AŞ');
  await page.getByRole('button', { name: 'Önizlemeyi hazırla' }).click();
  await page.getByRole('button', { name: 'Aktarımı onayla' }).click(); await expect(page.getByRole('status')).toContainText('Aktarım tamamlandı');
  await page.goto('/dashboard'); await expect(page.locator('.kpi').first()).toBeVisible();
  await page.screenshot({ path: 'test-results/desktop-dashboard.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/reports'); await expect(page.locator('.kpi').first()).toBeVisible();
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 249, 246)');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/mobile-reports.png', fullPage: true });
});
